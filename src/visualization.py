def render_mode_indicator(mode: AnalysisMode):
    """Display an indicator showing whether results are from live AI or demo."""
    if mode == AnalysisMode.DEMONSTRATION:
        st.info("🏷️ **Demonstration Mode** — These results are pre-defined examples, "
                "not derived from your uploaded image.")
    else:
        st.success("🤖 **Live AI Analysis** — Results generated by Google Gemini.")


def render_metric_card(label: str, value: str, color: str = "#667eea"):
    """Render a styled metric card."""
    st.markdown(f"""
    <div class="metric-card" style="background: linear-gradient(135deg, {color} 0%, {color}dd 100%);">
        <h3>{label}</h3>
        <div class="metric-value">{value}</div>
    </div>
    """, unsafe_allow_html=True)


def render_safety_score(score: int, status: OverallStatus):
    """Render safety score with color-coded status."""
    if score >= 80:
        color = "#28a745"
        delta_color = "normal"
    elif score >= 60:
        color = "#ffc107"
        delta_color = "normal"
    elif score >= 40:
        color = "#fd7e14"
        delta_color = "inverse"
    else:
        color = "#dc3545"
        delta_color = "inverse"

    col1, col2 = st.columns(2)
    with col1:
        render_metric_card("Safety Score", f"{score}/100", color)
    with col2:
        status_class = {
            OverallStatus.SAFE: "status-safe",
            OverallStatus.NEEDS_ATTENTION: "status-attention",
            OverallStatus.CRITICAL: "status-critical",
            OverallStatus.UNSAFE: "status-unsafe",
        }.get(status, "status-attention")
        render_metric_card("Overall Status", f'<span class="{status_class}">{status.value}</span>', color)


def render_ppe_checklist(ppe_detection: dict):
    """Render PPE detection results as a formatted checklist."""
    st.subheader("👷 PPE Detection Checklist")

    ppe_icons = {
        PPEStatus.OBSERVED: ("✅", "ppe-observed"),
        PPEStatus.NOT_OBSERVED: ("❌", "ppe-not-observed"),
        PPEStatus.UNKNOWN: ("❓", "ppe-unknown"),
        PPEStatus.NOT_APPLICABLE: ("➖", "ppe-na"),
    }

    ppe_labels = {
        "helmet": "Safety Helmet",
        "high_visibility_vest": "High-Visibility Vest",
        "safety_footwear": "Safety Footwear",
        "safety_harness": "Safety Harness",
    }

    for key, item in ppe_detection.items():
        label = ppe_labels.get(key, key.replace("_", " ").title())
        icon, css_class = ppe_icons.get(item.status, ("❓", "ppe-unknown"))
        confidence_str = f" (confidence: {item.confidence:.0%})" if item.confidence is not None else ""

        with st.container():
            col1, col2, col3 = st.columns([0.5, 2, 3])
            with col1:
                st.markdown(f"<span style='font-size:1.5rem'>{icon}</span>", unsafe_allow_html=True)
            with col2:
                st.markdown(f"**{label}**")
                st.caption(f"Status: {item.status.value}{confidence_str}")
            with col3:
                if item.notes:
                    st.caption(item.notes)


def render_hazard_table(hazards: list):
    """Render hazards as a formatted table."""
    if not hazards:
        st.success("✅ No significant hazards identified.")
        return

    st.subheader("⚠️ Identified Hazards")

    severity_icons = {
        SeverityLevel.LOW: "🟢",
        SeverityLevel.MEDIUM: "🟡",
        SeverityLevel.HIGH: "🟠",
        SeverityLevel.CRITICAL: "🔴",
    }

    for i, hazard in enumerate(hazards, 1):
        icon = severity_icons.get(hazard.severity, "⚪")
        with st.expander(f"{icon} {hazard.hazard} — Severity: {hazard.severity.value}", expanded=(i <= 3)):
            if hazard.evidence:
                st.markdown(f"**Evidence:** {hazard.evidence}")
            if hazard.corrective_action:
                st.markdown(f"**Corrective Action:** {hazard.corrective_action}")


def render_crack_results(result: CrackDiagnosticsResult):
    """Render crack diagnostics results."""
    col1, col2, col3 = st.columns(3)
    with col1:
        defect_color = "#dc3545" if result.severity in (SeverityLevel.HIGH, SeverityLevel.CRITICAL) else "#ffc107"
        render_metric_card("Defect Type", result.defect_type.value, defect_color)
    with col2:
        render_metric_card("Severity", result.severity.value,
                          "#dc3545" if result.severity == SeverityLevel.CRITICAL else "#fd7e14")
    with col3:
        render_metric_card("Urgency", result.urgency.value,
                          "#dc3545" if result.urgency == UrgencyLevel.IMMEDIATE else "#1E88E5")

    # Width estimate
    st.subheader("📏 Crack Width Estimate")
    if result.estimated_width_mm is not None:
        st.metric("Estimated Width", f"{result.estimated_width_mm:.2f} mm")
    else:
        st.warning("⚠️ **Not measurable from this image** — No reliable scale reference available. "
                   "Use a crack-width gauge for accurate measurement.")

    # Possible causes
    if result.possible_causes:
        st.subheader("🔍 Possible Causes")
        for cause in result.possible_causes:
            st.markdown(f"- {cause}")

    # Evidence
    if result.evidence:
        st.subheader("📋 Evidence")
        for ev in result.evidence:
            st.markdown(f"- {ev}")

    # Recommended actions
    if result.recommended_actions:
        st.subheader("🛠️ Recommended Actions")
        for action in result.recommended_actions:
            st.markdown(f"- {action}")

    # Professional review warning
    if result.professional_review_required:
        st.error("🏗️ **Professional Review Required** — This preliminary assessment does not replace "
                 "inspection by a qualified structural engineer. If this crack appears potentially "
                 "serious, is widening, or is associated with displacement, seek prompt professional evaluation.")


def render_construction_plan(plan: ConstructionPlan):
    """Render construction plan with costs and material estimates."""
    st.subheader("💰 Construction Cost Summary")

    col1, col2, col3 = st.columns(3)
    with col1:
        render_metric_card("Estimated Budget", format_inr(plan.estimated_budget_inr), "#1E88E5")
    with col2:
        render_metric_card("Expenditure Incurred", format_inr(plan.expenditure_incurred_inr), "#28a745")
    with col3:
        render_metric_card("Remaining Budget", format_inr(plan.remaining_budget_inr), "#fd7e14")

    # Progress bar
    st.subheader("📊 Project Completion")
    st.progress(plan.completion_percentage / 100)
    st.caption(f"**{plan.completion_percentage:.0f}%** complete — Current stage: **{plan.current_milestone}**")

    # Material estimates
    if plan.materials:
        st.subheader("🧱 Estimated Material Requirements")
        st.caption("⚠️ These are approximate estimates based on configurable assumptions. "
                   "Actual quantities depend on structural design, drawings, and specifications.")
        for mat in plan.materials:
            col1, col2, col3 = st.columns([2, 1, 3])
            with col1:
                st.metric(mat.material, f"{mat.estimated_quantity:,.0f} {mat.unit}")
            with col2:
                st.empty()
            with col3:
                st.caption(f"Assumption: {mat.assumption}")


def render_valuation(valuation: ValuationResult):
    """Render property valuation results."""
    st.subheader("🏠 Property Valuation Estimate")

    cols = st.columns(3)
    with cols[0]:
        render_metric_card("Construction Cost", format_inr(valuation.construction_cost_inr), "#1E88E5")
    with cols[1]:
        if valuation.land_cost_inr:
            render_metric_card("Land Cost", format_inr(valuation.land_cost_inr), "#28a745")
        else:
            render_metric_card("Land Cost", "Not Provided", "#6c757d")
    with cols[2]:
        if valuation.total_asset_value_inr:
            render_metric_card("Total Asset Value", format_inr(valuation.total_asset_value_inr), "#764ba2")
        else:
            render_metric_card("Total Asset Value", "N/A", "#6c757d")

    if valuation.estimated_property_value_inr:
        st.metric("Estimated Property Value (Market-Based)", format_inr(valuation.estimated_property_value_inr))

    st.markdown(f"**Valuation Method:** {valuation.valuation_method}")

    if valuation.assumptions:
        with st.expander("📋 Assumptions & Disclaimers"):
            for assumption in valuation.assumptions:
                st.markdown(f"- {assumption}")
            st.warning("⚠️ This is a preliminary estimate, not a certified property valuation. "
                       "Actual property value depends on professional appraisal, market conditions, "
                       "and local regulations.")


def render_milestone_progress(completion_percentage: float):
    """Render construction milestone progress indicator."""
    st.subheader("🏗️ Construction Milestones")
    milestones = get_milestones()

    for milestone in milestones:
        start, end = milestone.percentage_range
        if completion_percentage >= end:
            icon = "✅"
            css = "milestone-complete"
        elif completion_percentage >= start:
            icon = "🔵"
            css = "milestone-active"
        else:
            icon = "⬜"
            css = ""

        st.markdown(
            f'<div class="milestone-item {css}">'
            f'{icon} <strong>{milestone.name}</strong> ({start}%–{end}%) '
            f'<br><small>{milestone.description}</small></div>',
            unsafe_allow_html=True
        )

    st.caption("ℹ️ The completion percentage is a simplified overall indicator. "
               "It does not independently verify that each milestone is complete.")


def render_weather_advisory(advisory: WeatherAdvisory):
    """Render weather-aware safety advisory."""
    risk_colors = {
        RiskLevel.LOW: "#28a745",
        RiskLevel.MODERATE: "#ffc107",
        RiskLevel.HIGH: "#fd7e14",
        RiskLevel.EXTREME: "#dc3545",
    }
    risk_icons = {
        RiskLevel.LOW: "🟢",
        RiskLevel.MODERATE: "🟡",
        RiskLevel.HIGH: "🟠",
        RiskLevel.EXTREME: "🔴",
    }

    col1, col2 = st.columns(2)
    with col1:
        condition_icons = {
            "High Wind": "💨",
            "Heavy Rain": "🌧️",
            "Extreme Heat": "🔥",
            "Normal": "☀️",
        }
        icon = condition_icons.get(advisory.condition.value, "🌤️")
        render_metric_card("Weather Condition", f"{icon} {advisory.condition.value}", "#1E88E5")
    with col2:
        r_icon = risk_icons.get(advisory.risk_level, "⚪")
        r_color = risk_colors.get(advisory.risk_level, "#6c757d")
        render_metric_card("Risk Level", f"{r_icon} {advisory.risk_level.value}", r_color)

    # Alerts
    if advisory.alerts:
        st.subheader("🚨 Safety Alerts")
        for alert in advisory.alerts:
            severity_icon = {
                SeverityLevel.LOW: "ℹ️",
                SeverityLevel.MEDIUM: "⚠️",
                SeverityLevel.HIGH: "🔶",
                SeverityLevel.CRITICAL: "🚨",
            }.get(alert.priority, "⚠️")
            st.warning(f"{severity_icon} **{alert.category}:** {alert.message}")

    # Preventive actions
    if advisory.preventive_actions:
        st.subheader("🛡️ Preventive Actions")
        for action in advisory.preventive_actions:
            st.markdown(f"- {action}")

    # Checklist
    if advisory.checklist:
        st.subheader("✅ Safety Checklist")
        for item in advisory.checklist:
            st.checkbox(item.item, value=item.checked, key=f"checklist_{item.item[:30]}")

    # General notes
    if advisory.general_notes:
        with st.expander("📝 General Notes"):
            for note in advisory.general_notes:
                st.markdown(f"- {note}")


